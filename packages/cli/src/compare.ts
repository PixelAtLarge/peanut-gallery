import type { Proposal } from '@peanut-gallery/core';

export interface ComparePair {
  label: string;
  before: string; // relative path from the compare page
  after: string;
}

const esc = (s: string) => s.replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]!);

/** Self-contained before/after page with side-by-side, slider and toggle views. */
export function renderComparePage(proposal: Proposal, pairs: ComparePair[], meta: { prUrl?: string; issueNumbers: number[]; repo: string }): string {
  const issues = meta.issueNumbers.map((n) => `<a href="https://github.com/${meta.repo}/issues/${n}">#${n}</a>`).join(', ');
  return `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><title>${esc(proposal.title)} — before / after</title>
<meta name="viewport" content="width=device-width,initial-scale=1">
<style>
  :root{color-scheme:light;font-family:ui-sans-serif,system-ui,-apple-system,Segoe UI,Roboto,sans-serif;--line:#e6e6e6}
  body{margin:0;background:#fafafa;color:#111}
  header{padding:24px 32px;border-bottom:1px solid var(--line);background:#fff}
  h1{margin:0 0 6px;font-size:20px}
  .meta{color:#666;font-size:13px}
  .summary{max-width:70ch;margin:10px 0 0;font-size:14px;line-height:1.5}
  main{padding:24px 32px;display:grid;gap:32px}
  section{background:#fff;border:1px solid var(--line);border-radius:12px;overflow:hidden}
  section h2{margin:0;padding:12px 16px;font-size:14px;border-bottom:1px solid var(--line);display:flex;justify-content:space-between;align-items:center}
  .views{display:flex;gap:4px}
  .views button{border:1px solid var(--line);background:#fff;border-radius:6px;padding:4px 10px;font-size:12px;cursor:pointer}
  .views button[aria-pressed=true]{background:#111;color:#fff;border-color:#111}
  .side{display:grid;grid-template-columns:1fr 1fr;gap:1px;background:var(--line)}
  .side figure{margin:0;background:#fff;padding:12px}
  .side figcaption{font-size:12px;font-weight:600;letter-spacing:.04em;text-transform:uppercase;color:#666;margin-bottom:8px}
  .side img{display:block;max-width:100%;height:auto;border:1px solid var(--line);border-radius:6px}
  .slider{position:relative;overflow:hidden;background:#fff;padding:12px;display:none}
  .slider .stage{position:relative;display:inline-block;max-width:100%}
  .slider img{display:block;max-width:100%;height:auto}
  .slider .top{position:absolute;inset:0;overflow:hidden;width:50%}
  .slider .top img{max-width:none}
  .slider input{position:absolute;inset:0;width:100%;height:100%;opacity:0;cursor:ew-resize;margin:0}
  .slider .bar{position:absolute;top:0;bottom:0;left:50%;width:2px;background:#f5b64f;pointer-events:none}
  .toggle{display:none;padding:12px;background:#fff}
  .toggle img{display:block;max-width:100%;height:auto;border:1px solid var(--line);border-radius:6px}
  .toggle .hint{font-size:12px;color:#666;margin-top:6px}
  section[data-view=slider] .side,section[data-view=toggle] .side{display:none}
  section[data-view=slider] .slider{display:block}
  section[data-view=toggle] .toggle{display:block}
  footer{padding:16px 32px;color:#666;font-size:12px}
</style></head>
<body>
<header>
  <h1>${esc(proposal.title)}</h1>
  <div class="meta">Proposal <code>${esc(proposal.id)}</code> · from ${issues}${meta.prUrl ? ` · <a href="${esc(meta.prUrl)}">pull request</a>` : ''} · effort ${esc(proposal.effort)} · confidence ${(proposal.confidence * 100).toFixed(0)}%</div>
  <p class="summary">${esc(proposal.summary)}</p>
</header>
<main>
${pairs
  .map(
    (p, i) => `<section data-view="side" id="pair-${i}">
  <h2><span>${esc(p.label)}</span><span class="views"><button aria-pressed="true" data-v="side">Side by side</button><button data-v="slider">Slider</button><button data-v="toggle">Toggle</button></span></h2>
  <div class="side">
    <figure><figcaption>Before</figcaption><img src="${esc(p.before)}" alt="Before: ${esc(p.label)}"></figure>
    <figure><figcaption>After</figcaption><img src="${esc(p.after)}" alt="After: ${esc(p.label)}"></figure>
  </div>
  <div class="slider"><div class="stage"><img src="${esc(p.after)}" alt=""><div class="top"><img src="${esc(p.before)}" alt=""></div><div class="bar"></div><input type="range" min="0" max="100" value="50" aria-label="Reveal"></div></div>
  <div class="toggle"><img src="${esc(p.before)}" data-before="${esc(p.before)}" data-after="${esc(p.after)}" alt=""><div class="hint">Showing <b>before</b> — click image or press space to toggle</div></div>
</section>`,
  )
  .join('\n')}
</main>
<footer>Generated by peanut-gallery. Reply on the issue with “after” or “before”, or react 👍 / 👎 on the comparison comment.</footer>
<script>
document.querySelectorAll('section').forEach(s=>{
  s.querySelectorAll('.views button').forEach(b=>b.onclick=()=>{s.dataset.view=b.dataset.v;s.querySelectorAll('.views button').forEach(x=>x.setAttribute('aria-pressed',x===b));});
  const r=s.querySelector('.slider input'),top=s.querySelector('.slider .top'),bar=s.querySelector('.slider .bar'),stage=s.querySelector('.slider .stage');
  const sync=()=>{top.style.width=r.value+'%';bar.style.left=r.value+'%';top.querySelector('img').style.width=stage.clientWidth+'px';};
  r.oninput=sync;new ResizeObserver(sync).observe(stage);
  const t=s.querySelector('.toggle img'),h=s.querySelector('.toggle .hint');let after=false;
  const flip=()=>{after=!after;t.src=after?t.dataset.after:t.dataset.before;h.innerHTML='Showing <b>'+(after?'after':'before')+'</b> — click image or press space to toggle';};
  t.onclick=flip;document.addEventListener('keydown',e=>{if(e.code==='Space'&&s.dataset.view==='toggle'){e.preventDefault();flip();}});
});
</script>
</body></html>`;
}

/** Compact static page used to render the PR summary PNG (no controls). */
export function renderSummaryPage(proposal: Proposal, pairs: ComparePair[]): string {
  return `<!doctype html><html><head><meta charset="utf-8"><style>
  body{margin:0;padding:24px;background:#fff;font-family:ui-sans-serif,system-ui,sans-serif;color:#111;width:1352px}
  h1{font-size:18px;margin:0 0 16px}
  .pair{display:grid;grid-template-columns:1fr 1fr;gap:16px;margin-bottom:20px}
  .pair>div{border:1px solid #e6e6e6;border-radius:8px;padding:10px}
  .cap{font-size:11px;letter-spacing:.06em;text-transform:uppercase;color:#666;margin-bottom:6px}
  img{display:block;max-width:100%;height:auto}
  .label{font-size:13px;font-weight:600;margin:0 0 6px}
  </style></head><body><h1>${esc(proposal.title)}</h1>
  ${pairs.map((p) => `<p class="label">${esc(p.label)}</p><div class="pair"><div><div class="cap">Before</div><img src="${esc(p.before)}"></div><div><div class="cap">After</div><img src="${esc(p.after)}"></div></div>`).join('')}
  </body></html>`;
}

export interface OptionColumn {
  label: string; // "A"
  title: string; // option title
  summary: string;
  /** image paths per target, same order as `targets` */
  images: string[];
  prUrl?: string;
}

/** before | A | B | C grid, one row per screenshot target. Used for the variants round. */
export function renderOptionsPage(
  proposal: Pick<Proposal, 'title' | 'summary'>,
  targets: string[],
  before: string[],
  options: OptionColumn[],
  opts: { compact?: boolean } = {},
): string {
  const cols = 1 + options.length;
  const head = opts.compact
    ? `<style>body{margin:0;padding:24px;background:#fff;font-family:ui-sans-serif,system-ui,sans-serif;color:#111;width:${Math.min(1600, 360 * cols + 48)}px}</style>`
    : `<style>body{margin:0;padding:24px 32px;background:#fafafa;font-family:ui-sans-serif,system-ui,sans-serif;color:#111}</style>`;
  return `<!doctype html><html lang="en"><head><meta charset="utf-8"><title>${esc(proposal.title)} — options</title>${head}
<style>
  h1{font-size:18px;margin:0 0 4px} .sub{color:#666;font-size:13px;margin:0 0 16px}
  .grid{display:grid;grid-template-columns:repeat(${cols},minmax(0,1fr));gap:12px;align-items:start}
  .hd{font-size:12px;letter-spacing:.06em;text-transform:uppercase;color:#666;padding:6px 0}
  .hd b{display:inline-block;background:#111;color:#fff;border-radius:6px;padding:1px 7px;margin-right:6px;letter-spacing:0}
  .hd .t{display:block;text-transform:none;letter-spacing:0;color:#111;font-weight:600;font-size:13px;margin-top:2px}
  .hd .s{display:block;text-transform:none;letter-spacing:0;color:#666;font-size:12px;font-weight:400;margin-top:2px;line-height:1.35}
  .row{font-size:13px;font-weight:600;grid-column:1/-1;margin-top:10px;padding-top:10px;border-top:1px solid #e6e6e6}
  .cell{border:1px solid #e6e6e6;border-radius:8px;padding:8px;background:#fff}
  img{display:block;max-width:100%;height:auto}
  a{color:#4f6df5;font-size:12px}
</style></head><body>
<h1>${esc(proposal.title)}</h1><p class="sub">${esc(proposal.summary)}</p>
<div class="grid">
  <div class="hd">Before</div>
  ${options.map((o) => `<div class="hd"><b>${esc(o.label)}</b>option<span class="t">${esc(o.title)}</span><span class="s">${esc(o.summary)}</span>${o.prUrl && !opts.compact ? `<a href="${esc(o.prUrl)}">pull request</a>` : ''}</div>`).join('')}
  ${targets
    .map(
      (t, i) =>
        `<div class="row">${esc(t)}</div><div class="cell"><img src="${esc(before[i] ?? '')}" alt="Before"></div>` +
        options.map((o) => `<div class="cell"><img src="${esc(o.images[i] ?? '')}" alt="Option ${esc(o.label)}"></div>`).join(''),
    )
    .join('')}
</div></body></html>`;
}
